SELECT
    id AS '使用者ID',
    name AS '姓名',
    grp AS '群組',
    Approver AS '審核者權限(0=否,1=是)',
    denyf AS '停用(0=啟用,1=停用)'
FROM [User]
WHERE denyf = 0  -- 只顯示啟用的使用者
ORDER BY id
GO

